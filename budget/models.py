"""SQLAlchemy models.

Phase 0 scope: reference data, the transaction ledger, opening balances and budgets --
everything the reconciliation gate needs. The feature-module tables (projection, payslip,
card, cycling) arrive with their phases; adding tables to SQLite later is free, it is
altering existing ones that hurts.

Money is stored as INTEGER pence via the Money type below. SQLite has no decimal type, so
a REAL column would reintroduce exactly the float artefacts the workbook already suffers
from (1530.0000000000146). Integers keep SUM() exact, which matters because every balance
in this application is a sum.
"""

from __future__ import annotations

import datetime as dt
from decimal import Decimal, ROUND_HALF_UP

from sqlalchemy import (
    Boolean,
    CheckConstraint,
    Date,
    DateTime,
    ForeignKey,
    Integer,
    String,
    Text,
    TypeDecorator,
    UniqueConstraint,
    func,
    text,
)
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column, relationship

PENCE = Decimal("0.01")


class Money(TypeDecorator):
    """Decimal pounds in Python, integer pence in the database."""

    impl = Integer
    cache_ok = True

    def process_bind_param(self, value, dialect):
        if value is None:
            return None
        return int(Decimal(str(value)).quantize(PENCE, rounding=ROUND_HALF_UP) * 100)

    def process_result_value(self, value, dialect):
        if value is None:
            return None
        return (Decimal(value) / 100).quantize(PENCE)


class Base(DeclarativeBase):
    pass


# A random 16-byte hex string, generated by SQLite so it applies to rows inserted by any
# route. This is the sync identity for cross-machine merges (DESIGN.md 6.3.3); the integer
# primary key stays for joins and readability.
_UID_DEFAULT = text("lower(hex(randomblob(16)))")


def _uid_column() -> Mapped[str]:
    return mapped_column(String(32), unique=True, nullable=False, server_default=_UID_DEFAULT)


