class CyclingRate(Base):
    """What a day's cycling saves, by kind, effective-dated.

    Was a nested IF inside the Cycling tab's L column -- IF(commute, 10.5, IF(band, 8.9,
    IF(gym, 4.6, 0))) -- so a fare rise meant either rewriting every historic row or
    accepting that old rows now claimed the new fare. Dating the rate fixes both: history
    keeps the fare that applied, and a rise is one new row.
    """

    __tablename__ = "cycling_rate"

    kind: Mapped[str] = mapped_column(String(16), primary_key=True)
    effective_from: Mapped[dt.date] = mapped_column(Date, primary_key=True)
    amount: Mapped[Decimal] = mapped_column(Money, nullable=False)

    __table_args__ = (
        CheckConstraint("kind IN ('commute','band','gym')", name="ck_cycling_rate_kind"),
    )


