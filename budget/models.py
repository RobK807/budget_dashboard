class Account(Base):
    __tablename__ = "account"

    id: Mapped[int] = mapped_column(primary_key=True)
    uid: Mapped[str] = _uid_column()
    name: Mapped[str] = mapped_column(String(64), unique=True, nullable=False)
    short_code: Mapped[str] = mapped_column(String(16), unique=True, nullable=False)
    # 'bank' or 'credit_card'. Determines posting sign: a credit card balance is positive
    # debt, so a debit increases it. Derived from the month-tab row-4 formula on import.
    type: Mapped[str] = mapped_column(String(16), nullable=False)

    is_savings: Mapped[bool] = mapped_column(Boolean, nullable=False, default=False)
    savings_limit: Mapped[Decimal | None] = mapped_column(Money)
    is_investment: Mapped[bool] = mapped_column(Boolean, nullable=False, default=False)
    investment_limit: Mapped[Decimal | None] = mapped_column(Money)
    is_isa: Mapped[bool] = mapped_column(Boolean, nullable=False, default=False)
    # Earmarked pots -- money that is nominally saved but already spoken for. The Summary
    # tab's 'Less SC & Wed' column subtracted these by hand; flagging the accounts means the
    # column follows when a pot is added, which the workbook's header did not (Tembo joined
    # in June and the label was never updated).
    exclude_from_savings: Mapped[bool] = mapped_column(
        Boolean, nullable=False, default=False
    )

    # Credit cards only: the day the statement is issued and the day the direct debit is
    # taken. Month-tab rows 48 and 50, which held them per month even though they never
    # varied by month.
    statement_day: Mapped[int | None] = mapped_column(Integer)
    payment_day: Mapped[int | None] = mapped_column(Integer)

    display_order: Mapped[int | None] = mapped_column(Integer)
    # Effective dating replaces the twelve per-month offset columns in Selections!Z:AK and
    # removes the need for update_months entirely (DESIGN.md 3.2).
    valid_from: Mapped[dt.date] = mapped_column(Date, nullable=False)
    valid_to: Mapped[dt.date | None] = mapped_column(Date)

    __table_args__ = (
        CheckConstraint("type IN ('bank','credit_card')", name="ck_account_type"),
    )

    def __repr__(self) -> str:
        return f"<Account {self.name!r} {self.type}>"


